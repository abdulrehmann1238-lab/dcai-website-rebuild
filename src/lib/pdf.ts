/**
 * Generates a valid minimal PDF Blob and triggers download in the browser.
 * Directly fulfills PRD Section 10.8 & 17 without heavy PDF libraries.
 */
export function downloadSamplePdf(mpn: string, docTitle: string) {
  const content = `%PDF-1.4
1 0 obj
<< /Type /Catalog /Pages 2 0 R >>
endobj
2 0 obj
<< /Type /Pages /Kids [3 0 R] /Count 1 >>
endobj
3 0 obj
<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>
endobj
4 0 obj
<< /Length 280 >>
stream
BT
/F1 22 Tf
50 720 Td
(DCAI - DIGICOM CONTROLS & AUTOMATION INC.) Tj
/F1 14 Tf
0 -40 Td
(${mpn} - TECHNICAL DOCUMENTATION) Tj
/F1 10 Tf
0 -25 Td
(Document: ${docTitle.replace(/[()]/g, '')}) Tj
0 -20 Td
(Date: March 2026 | Certified Distribution Copy) Tj
0 -30 Td
(Notice: This is a sample technical sheet generated by the DCAI product repository demo.) Tj
0 -20 Td
(For live ETS databases or official engineering submittals, contact DCAI technical support.) Tj
ET
endstream
endobj
5 0 obj
<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>
endobj
xref
0 6
0000000000 65535 f 
0000000009 00000 n 
0000000058 00000 n 
0000000115 00000 n 
0000000244 00000 n 
0000000576 00000 n 
trailer
<< /Size 6 /Root 1 0 R >>
startxref
655
%%EOF`;

  const blob = new Blob([content], { type: 'application/pdf' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${mpn.toUpperCase()}_Datasheet.pdf`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
